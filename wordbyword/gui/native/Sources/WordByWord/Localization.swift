/// Interface language only. Workflow arguments, document content, and engine output
/// retain their original values regardless of the language selected here.
enum StudioLanguage: String, Codable, CaseIterable, Identifiable, Sendable {
    case english = "en"
    case korean = "ko"

    var id: String { rawValue }
    var nativeName: String { self == .korean ? "한국어" : "English" }
    var locale: Locale { Locale(identifier: self == .korean ? "ko_KR" : "en_US") }

    func text(_ english: String) -> String {
        guard self == .korean else { return english }
        return StudioLocalization.korean[english]
            ?? StudioLocalization.caseInsensitiveKorean[english.lowercased()]
            ?? english
    }

    func format(_ english: String, _ arguments: CVarArg...) -> String {
        formatted(english, arguments: arguments)
    }

    func formatted(_ english: String, arguments: [CVarArg]) -> String {
        String(format: text(english), locale: locale, arguments: arguments)
    }

    func phase(_ raw: String) -> String {
        let key = raw.replacingOccurrences(of: "_", with: " ")
        return self == .korean ? text(key) : key.uppercased()
    }

    func artifactLabel(_ artifact: StudioArtifact) -> String {
        guard self == .korean else { return artifact.label }
        return StudioLocalization.artifactLabels[artifact.id] ?? artifact.label
    }

    func previewText(_ preview: PreviewDocument) -> String {
        if preview.isMigration { return migrationText(preview.text) }
        // PDF previews contain metadata, not extracted document text. Only
        // localize that explanation when the bridge supplied its typed size.
        guard self == .korean, URL(fileURLWithPath: preview.path).pathExtension.lowercased() == "pdf",
              let byteCount = preview.byteCount, byteCount >= 0 else { return preview.text }
        return format("PDF document · %@ bytes\n\nOpen the original file to view its pages.",
                      byteCount.formatted(.number.locale(locale)))
    }

    /// Only the bridge's explanatory labels are localized. Paths and unknown
    /// diagnostic lines are copied verbatim, including their indentation.
    func migrationText(_ raw: String) -> String {
        guard self == .korean else { return raw }
        return raw.components(separatedBy: "\n").map { line in
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if let count = Int(trimmed.replacingOccurrences(of: " proposed move(s).", with: "")),
               trimmed == "\(count) proposed move(s)." {
                return format("%d proposed move(s).", count)
            }
            let indentation = String(line.prefix(while: { $0 == " " || $0 == "\t" }))
            let translated = text(trimmed)
            return translated == trimmed ? line : indentation + translated
        }.joined(separator: "\n")
    }
}

private struct StudioLanguageKey: EnvironmentKey {
    static let defaultValue = StudioLanguage.english
}

extension EnvironmentValues {
    var studioLanguage: StudioLanguage {
        get { self[StudioLanguageKey.self] }
        set { self[StudioLanguageKey.self] = newValue }
    }
}

